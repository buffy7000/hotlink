function classify_hotdeal_category($title) {
    if (empty($title)) return 'etc';

    $keywordMap = hotdeal_category_keywords();
    foreach ($keywordMap as $category => $keywords) {
        foreach ($keywords as $keyword) {
            if (mb_stripos($title, $keyword) !== false) {
                return $category;
            }
        }
    }

    return 'etc';
}
